#!/usr/bin/env python3
"""Writes the recompiler config for a modded build: the game's config plus the mods' patches and hooks.

tools/modrecomp lists every RECOMP_PATCH, RECOMP_HOOK and RECOMP_HOOK_RETURN of the mods in
mods_hooks.json. Each becomes a [[patches.hook]] at the start of the game function (before the
config's own hooks, which sit at the function's first instruction):
- a patch calls the mod's function in place of the game's, then returns;
- a hook calls the mod's function with a copy of the context (mod_call_hook);
- a return hook does the same before every return of the game function (at_return), in reverse
  mod order as N64ModernRuntime runs them.

usage: gen_mod_config.py <game config .toml> <mods_hooks.json> <output .toml> <recomp output dir>
"""

import json
import os
import re
import sys
import tomllib
from pathlib import Path


def fail(msg):
    sys.exit(f"gen_mod_config: error: {msg}")


def main():
    base_path, hooks_path, out_path, recomp_dir = map(Path, sys.argv[1:5])
    base_text = base_path.read_text()
    base = tomllib.loads(base_text)
    hooks = json.loads(hooks_path.read_text())

    # Paths in [input] are relative to the config file.
    def rebase(match):
        key, value = match.group(1), match.group(2)
        target = recomp_dir if key == "output_func_path" else base_path.parent / value
        rel = os.path.relpath(os.path.normpath(target), out_path.parent)
        return f'{key} = "{Path(rel).as_posix()}"'
    text = re.sub(r'^(rom_file_path|symbols_file_path|output_func_path)\s*=\s*"([^"]*)"', rebase, base_text, flags=re.M)
    # Mod hooks run arbitrary code against the context, so modded builds keep every register in it.
    text = re.sub(r'^(regcache\s*=\s*)"[^"]*"', r'\1"off"', text, flags=re.M)
    text = re.sub(r'^(abi_poison\s*=\s*)\w+', r'\1false', text, flags=re.M)
    text = re.sub(r'^(abi_trace\s*=\s*)\w+', r'\1false', text, flags=re.M)
    text = re.sub(r'^abi_report\s*=.*\n', '', text, flags=re.M)
    text = re.sub(r'^(delay_once|skip_saves|lookup_cache|ret_trim|fpr_abi_sync)\s*=\s*\w+', r'\1 = false', text, flags=re.M)
    text = re.sub(r'^(inline_leaves)\s*=\s*\w+', r'\1 = 0', text, flags=re.M)

    patches = base.get("patches", {})
    blocked = set(patches.get("stubs", [])) | set(patches.get("ignored", []))
    base_hooks = {}
    for h in patches.get("hook", []):
        base_hooks.setdefault(h["func"], []).append(h["text"])

    mod_order = list(dict.fromkeys(h["mod"] for h in hooks))
    by_func = {}
    for h in hooks:
        by_func.setdefault(h["func"], []).append(h)

    out = [text.rstrip("\n"), "", "# --- Mods (generated by scripts/gen_mod_config.py) ---"]
    for func, entries in by_func.items():
        if func in blocked:
            fail(f"a mod hooks or patches {func}, which config/{base_path.name} stubs or ignores")
        patch = [e for e in entries if e["kind"] == "patch"]
        entry_hooks = [e for e in entries if e["kind"] == "hook"]
        return_hooks = sorted((e for e in entries if e["kind"] == "return_hook"), key=lambda e: -mod_order.index(e["mod"]))
        if len(patch) > 1:
            fail(f"{func} is patched by more than one mod: " + ", ".join(e["mod"] for e in patch))
        if patch:
            for text in base_hooks.get(func, []):
                if not text.rstrip().endswith("return;"):
                    fail(f"{patch[0]['mod']} patches {func}, which the runtime needs to see run ({text})")

        texts = [f"mod_call_hook(rdram, ctx, {e['call']});" for e in entry_hooks]
        ret_texts = [f"mod_call_hook(rdram, ctx, {e['call']});" for e in return_hooks]
        if patch:
            texts.append(f"{patch[0]['call']}(rdram, ctx); " + " ".join(ret_texts) + (" " if ret_texts else "") + "return;")
        for t in texts:
            out += ["", "[[patches.hook]]", f'func = "{func}"', f'text = "{t}"']
        if not patch:
            for t in ret_texts:
                out += ["", "[[patches.hook]]", f'func = "{func}"', f'text = "{t}"', "at_return = true"]

    new_text = "\n".join(out) + "\n"
    if not out_path.exists() or out_path.read_text() != new_text:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(new_text)
    kinds = [h["kind"] for h in hooks]
    print(f"gen_mod_config: {kinds.count('patch')} patches, {kinds.count('hook')} hooks, "
          f"{kinds.count('return_hook')} return hooks on {len(by_func)} game functions")


if __name__ == "__main__":
    main()
