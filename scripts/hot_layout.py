#!/usr/bin/env python3
# Writes a linker-script fragment that places named functions at the front of the
# image. Refresh it with:
#   python3 scripts/hot_layout.py build/hot_funcs.ld scripts/hot_seed.txt build/hot_extra.txt
# hot_extra.txt is one function name per line (from scripts/profile.py). Missing files are skipped.
import sys

HEADER = """/* Generated by scripts/hot_layout.py. Do not edit.
   Each name is a -ffunction-sections input section. INSERT puts this block
   immediately before the rest of .text, so the hot code is contiguous. */
SECTIONS
{
  .text.hot :
  {
    . = ALIGN(32);
"""

FOOTER = """  }
}
INSERT BEFORE .text;
"""


def names_from(path):
    out = []
    try:
        lines = open(path, "r", errors="replace")
    except OSError:
        return out
    with lines as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            # profile.py lines look like "  12.30%  func_80022240" or a bare name.
            parts = line.split()
            name = parts[-1]
            if name.startswith("0x") or name.endswith("%"):
                continue
            out.append(name)
    return out


def main():
    if len(sys.argv) < 3:
        sys.exit("usage: hot_layout.py OUT.ld NAMES.txt [NAMES.txt...]")
    seen = []
    have = set()
    for path in sys.argv[2:]:
        for name in names_from(path):
            if name not in have:
                have.add(name)
                seen.append(name)
    if not seen:
        sys.exit("hot_layout: no function names")
    with open(sys.argv[1], "w", newline="\n") as f:
        f.write(HEADER)
        for name in seen:
            f.write("    *(.text.%s)\n" % name)
        f.write(FOOTER)
    print("hot_layout: %d functions -> %s" % (len(seen), sys.argv[1]))


if __name__ == "__main__":
    main()
