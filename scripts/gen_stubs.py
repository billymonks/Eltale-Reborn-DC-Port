#!/usr/bin/env python3
"""Generates the glue between the recompiled code and the runtime functions it calls.

The recompiler calls runtime-provided functions (osCreateThread_recomp, __ll_div_recomp, ...),
declaring most of them in funcs.h. This writes:
- a header declaring the ones funcs.h misses (force-included into the generated code), and
- a C file with a stub for every one the runtime doesn't define yet. Each stub reports its name
  and stops, so a run shows the next piece of libultra the runtime needs.

usage: gen_stubs.py <recomp output dir> <runtime src dir> <stubs .c> <decls .h>
"""

import re
import sys
from pathlib import Path

DECL = re.compile(r"^void (\w+)\(uint8_t\* rdram, recomp_context\* ctx\);", re.M)
DEF = re.compile(r"\bvoid\s+(\w+)\s*\(\s*uint8_t\s*\*\s*rdram\s*,\s*recomp_context\s*\*\s*ctx\s*\)\s*\{")
CALL = re.compile(r"^\s*(\w+)\(rdram, ctx\);", re.M)
NOT_FUNCS = {"LOOKUP_FUNC"}


def write_if_changed(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def main():
    recomp_dir, runtime_dir, stubs_path, decls_path = map(Path, sys.argv[1:5])

    declared = set(DECL.findall((recomp_dir / "funcs.h").read_text()))

    called = set()
    defined = set()
    for src in recomp_dir.glob("*.c"):
        text = src.read_text()
        defined.update(DEF.findall(text))
        called.update(CALL.findall(text))
    called -= NOT_FUNCS
    for src in list(runtime_dir.rglob("*.c")) + list(runtime_dir.rglob("*.cpp")):
        defined.update(DEF.findall(src.read_text()))

    undeclared = sorted(called - declared - defined)
    missing = sorted((declared | called) - defined)

    decls = ["// Generated by scripts/gen_stubs.py: runtime functions the generated code calls without declaring.",
             "#pragma once",
             '#include "recomp.h"',
             ""]
    decls += [f"void {name}(uint8_t* rdram, recomp_context* ctx);" for name in undeclared]
    write_if_changed(decls_path, "\n".join(decls) + "\n")

    stubs = ["// Generated by scripts/gen_stubs.py: runtime functions that aren't implemented yet.",
             '#include "runtime.h"',
             ""]
    stubs += [f'void {name}(uint8_t* rdram, recomp_context* ctx) {{ (void)rdram; (void)ctx; runtime_unimplemented("{name}"); }}'
              for name in missing]
    write_if_changed(stubs_path, "\n".join(stubs) + "\n")

    print(f"gen_stubs: {len(missing)} unimplemented runtime functions ({len(undeclared)} missing from funcs.h)")


if __name__ == "__main__":
    main()
